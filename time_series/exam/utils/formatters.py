"""
Модуль с утилитами для форматирования чисел и валют.

Предоставляет функции для красивого отображения финансовых данных.
"""


def format_currency(value: float) -> str:
    """
    Форматирует число как валюту в долларах США.
    
    Args:
        value: Числовое значение
    
    Returns:
        Отформатированная строка (например, "$1,234.56")
    """
    return f"${value:,.2f}"


def format_percentage(value: float) -> str:
    """
    Форматирует число как процент с знаком.
    
    Args:
        value: Числовое значение (например, 5.67 для 5.67%)
    
    Returns:
        Отформатированная строка (например, "+5.67%" или "-2.34%")
    """
    sign = "+" if value >= 0 else ""
    return f"{sign}{value:.2f}%"